//! kb-core: детерминированные примитивы, общие для всего проекта.
//!
//! `no_std`, ноль зависимостей — крейт физически не способен обзавестись
//! I/O, графикой или float'ами незаметно для ревью (§1, §3 ТЗ).
//! Всё, что здесь живёт, обязано давать бит-в-бит одинаковый результат
//! на любой платформе, включая wasm32.

#![no_std]
#![forbid(unsafe_code)]

/// SplitMix64 — финализирующий миксер. Не генератор с состоянием, а чистая
/// функция: одно и то же входное слово → одно и то же выходное. Именно
/// поэтому он наш базовый кирпич — «мир-как-функция» требует stateless-хешей,
/// а не последовательных RNG, порядок вызова которых пришлось бы хранить.
#[inline]
pub const fn splitmix64(z: u64) -> u64 {
    let z = z.wrapping_add(0x9E37_79B9_7F4A_7C15);
    let z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    let z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// Хеш точки 2D-решётки. Координаты кладутся в одно слово без знакового
/// расширения, сид подмешивается до миксера — соседние точки и соседние
/// сиды дают некоррелированные результаты.
#[inline]
pub const fn hash2(seed: u64, x: i32, y: i32) -> u32 {
    splitmix64(seed ^ (((x as u32 as u64) << 32) | (y as u32 as u64))) as u32
}

/// FNV-1a — хеш произвольных байтов. Используется тестами детерминизма
/// (§16: одинаковый сид → одинаковый хеш на native и wasm32).
pub fn fnv1a(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xCBF2_9CE4_8422_2325u64, |h, &b| {
        (h ^ b as u64).wrapping_mul(0x0000_0100_0000_01B3)
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Эталонные значения зафиксированы навсегда: их изменение означает
    /// слом всех существующих миров и допустимо только новой версией
    /// генератора (§4).
    #[test]
    fn determinism_anchors() {
        assert_eq!(splitmix64(0), 0xE220_A839_7B1D_CDAF);
        assert_eq!(hash2(1, -1, 1), hash2(1, -1, 1));
        assert_ne!(hash2(1, 0, 1), hash2(1, 1, 0)); // оси не симметричны
        assert_eq!(fnv1a(b"kb"), {
            let h = (0xCBF2_9CE4_8422_2325u64 ^ b'k' as u64)
                .wrapping_mul(0x0000_0100_0000_01B3);
            (h ^ b'b' as u64).wrapping_mul(0x0000_0100_0000_01B3)
        });
    }
}

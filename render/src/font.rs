//! Крошечный пиксельный шрифт 5×7 для подписей меню. Ноль ассетов (§4):
//! глифы — битовые строки прямо в коде. Хватает букв для ярлыков меню.

/// 7 строк по 5 бит (бит 4 — левый столбец). Только нужные буквы.
fn glyph(ch: u8) -> [u8; 7] {
    match ch {
        b'M' => [0b10001, 0b11011, 0b10101, 0b10101, 0b10001, 0b10001, 0b10001],
        b'E' => [0b11111, 0b10000, 0b10000, 0b11110, 0b10000, 0b10000, 0b11111],
        b'N' => [0b10001, 0b11001, 0b11001, 0b10101, 0b10011, 0b10011, 0b10001],
        b'U' => [0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b01110],
        b'P' => [0b11110, 0b10001, 0b10001, 0b11110, 0b10000, 0b10000, 0b10000],
        b'I' => [0b11111, 0b00100, 0b00100, 0b00100, 0b00100, 0b00100, 0b11111],
        b'X' => [0b10001, 0b10001, 0b01010, 0b00100, 0b01010, 0b10001, 0b10001],
        b'L' => [0b10000, 0b10000, 0b10000, 0b10000, 0b10000, 0b10000, 0b11111],
        b'S' => [0b01111, 0b10000, 0b10000, 0b01110, 0b00001, 0b00001, 0b11110],
        b'D' => [0b11110, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11110],
        b'T' => [0b11111, 0b00100, 0b00100, 0b00100, 0b00100, 0b00100, 0b00100],
        b'H' => [0b10001, 0b10001, 0b10001, 0b11111, 0b10001, 0b10001, 0b10001],
        b'R' => [0b11110, 0b10001, 0b10001, 0b11110, 0b10100, 0b10010, 0b10001],
        b'O' => [0b01110, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b01110],
        b'G' => [0b01110, 0b10001, 0b10000, 0b10111, 0b10001, 0b10001, 0b01110],
        _ => [0; 7], // пробел и прочее
    }
}

/// Рисует строку белым в RGBA-холст `buf` шириной `w` от (x, y),
/// шаг символа 6 px. Тексты ярлыков — латиница в верхнем регистре.
pub fn draw_text(buf: &mut [u8], w: usize, x: usize, y: usize, text: &str) {
    for (i, ch) in text.bytes().enumerate() {
        let g = glyph(ch);
        for (row, bits) in g.iter().enumerate() {
            for col in 0..5 {
                if bits >> (4 - col) & 1 == 1 {
                    let (px, py) = (x + i * 6 + col, y + row);
                    let o = (py * w + px) * 4;
                    if o + 4 <= buf.len() {
                        buf[o..o + 4].copy_from_slice(&[235, 235, 235, 255]);
                    }
                }
            }
        }
    }
}
